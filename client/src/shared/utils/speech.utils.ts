import { stripMarkdown } from "@/shared/utils/format.utils";
import { voiceService } from "@/shared/services/voice.service";
import type { SpeakController, SpeakOptions, SpeechRecognitionConstructor } from "@/shared/types/voice.types";

const win = typeof window !== "undefined" ? (window as unknown as Record<string, unknown>) : {};

/** Browser speech-to-text, when available (Chrome/Edge/Safari). */
export const SpeechRecognitionImpl = (win.SpeechRecognition || win.webkitSpeechRecognition) as SpeechRecognitionConstructor | undefined;
export const voiceInputSupported = Boolean(SpeechRecognitionImpl);
export const readAloudSupported = typeof window !== "undefined" && "speechSynthesis" in window;

/** Turns a SpeechRecognition error code into something a human can act on (null = stay silent). */
export async function describeVoiceError(code: string): Promise<string | null> {
  switch (code) {
    case "not-allowed":
    case "service-not-allowed":
      return "Microphone access is blocked. Click the 🔒 icon in the address bar and allow the microphone.";
    case "network": {
      // Brave ships the API but blocks the Google speech service behind it
      const nav = navigator as Navigator & { brave?: { isBrave?: () => Promise<boolean> } };
      const brave = await nav.brave?.isBrave?.().catch(() => false);
      return brave
        ? "Brave blocks Google's speech service, so voice typing can't work here. Use Chrome, Edge or Safari for the mic."
        : "Couldn't reach the speech service. Check your internet connection and try again.";
    }
    case "no-speech":
      return "Didn't hear anything — check your microphone and try again.";
    case "audio-capture":
      return "No microphone was found. Plug one in or pick another input in system settings.";
    case "language-not-supported":
      return "This language isn't supported for voice input in your browser.";
    default:
      return null; // "aborted" etc. are user-initiated
  }
}

/** Split text into sentence-ish pieces. */
const sentences = (text: string): string[] => text.match(/[^.!?।\n]+[.!?।]*\s*/g)?.map((c) => c.trim()).filter(Boolean) ?? [text];

/** Hard-wrap a piece that is longer than `max` at word boundaries. */
const wrap = (piece: string, max: number): string[] => {
  if (piece.length <= max) return [piece];
  const out: string[] = [];
  let rest = piece;
  while (rest.length > max) {
    let cut = rest.lastIndexOf(" ", max);
    if (cut < max / 2) cut = max;
    out.push(rest.slice(0, cut).trim());
    rest = rest.slice(cut);
  }
  return [...out, rest.trim()].filter(Boolean);
};

/**
 * Chunks for the TTS server. The FIRST chunk is short so audio starts quickly;
 * the rest are grouped into bigger pieces that are fetched while the previous one plays.
 */
export function toChunks(text: string, first = 140, rest = 300): string[] {
  const out: string[] = [];
  let cur = "";
  for (const s of sentences(text).flatMap((x) => wrap(x, rest))) {
    const limit = out.length === 0 ? first : rest;
    if (cur && `${cur} ${s}`.length > limit) {
      out.push(cur);
      cur = s;
    } else cur = cur ? `${cur} ${s}` : s;
  }
  if (cur) out.push(cur);
  return out;
}

function pickDeviceVoice(lang: string): SpeechSynthesisVoice | null {
  const voices = window.speechSynthesis.getVoices();
  const base = lang.split("-")[0];
  return voices.find((v) => v.lang === lang) || voices.find((v) => v.lang.replace("_", "-").startsWith(base)) || null;
}

/**
 * Speak `text` (markdown allowed) with the chosen voice.
 *  - voice "device": the browser's built-in speech synthesis (instant, offline)
 *  - any other id  : premium voice generated by the server (Gemini TTS), streamed chunk by chunk.
 *    If the server can't deliver, it falls back to the device voice.
 */
export function speak(text: string, { voice = "device", lang = "en-IN", onFallback }: SpeakOptions = {}): SpeakController {
  const plain = stripMarkdown(text);
  // Devanagari in the answer => Hindi voice, whatever the mic language is
  const speechLang = /[ऀ-ॿ]/.test(plain) ? "hi-IN" : lang;
  let cancelled = false;
  let audio: HTMLAudioElement | null = null;

  const cancel = () => {
    cancelled = true;
    audio?.pause();
    audio = null;
    window.speechSynthesis?.cancel();
  };

  const speakDevice = (t: string) =>
    new Promise<void>((resolve) => {
      const parts = sentences(t).flatMap((x) => wrap(x, 200)); // Chrome stops long utterances
      let i = 0;
      const next = () => {
        if (cancelled || i >= parts.length) return resolve();
        const u = new SpeechSynthesisUtterance(parts[i++]);
        u.lang = speechLang;
        const v = pickDeviceVoice(speechLang);
        if (v) u.voice = v;
        u.rate = 1.05;
        u.onend = next;
        u.onerror = () => resolve();
        window.speechSynthesis.speak(u);
      };
      next();
    });

  const play = (url: string) =>
    new Promise<void>((resolve) => {
      audio = new Audio(url);
      const end = () => {
        URL.revokeObjectURL(url);
        resolve();
      };
      audio.onended = end;
      audio.onerror = end;
      audio.play().catch(end);
    });

  const run = async () => {
    if (!plain) return;
    if (voice === "device") return speakDevice(plain);

    const chunks = toChunks(plain);
    const fetchChunk = (i: number) => voiceService.speak(voice, chunks[i]).then((blob) => URL.createObjectURL(blob));

    let next = fetchChunk(0);
    next.catch(() => {}); // handled below; avoids an "unhandled rejection" while we wait
    for (let i = 0; i < chunks.length; i++) {
      if (cancelled) return;
      let url: string;
      try {
        url = await next;
      } catch (error) {
        if (cancelled) return;
        onFallback?.(error);
        return speakDevice(chunks.slice(i).join(" "));
      }
      if (i + 1 < chunks.length) {
        next = fetchChunk(i + 1); // prefetch the next piece while this one plays
        next.catch(() => {});
      }
      if (cancelled) return URL.revokeObjectURL(url);
      await play(url);
    }
  };

  return { cancel, done: run().catch(() => {}) };
}

/** Short sample used by the voice picker's ▶ buttons. `onStart` fires when sound begins. */
export function previewVoice(voice: string, lang: string, { onStart }: { onStart?: () => void } = {}): SpeakController {
  if (voice === "device") {
    onStart?.();
    return speak("Hi, I'm your device voice. This is how I sound when I read your answers out loud.", { voice, lang });
  }
  let cancelled = false;
  let audio: HTMLAudioElement | null = null;
  const done = voiceService.preview(voice).then(
    (blob) =>
      new Promise<void>((resolve) => {
        if (cancelled) return resolve();
        const url = URL.createObjectURL(blob);
        audio = new Audio(url);
        const end = () => {
          URL.revokeObjectURL(url);
          resolve();
        };
        audio.onended = end;
        audio.onerror = end;
        onStart?.();
        audio.play().catch(end);
      }),
  );
  return {
    cancel: () => {
      cancelled = true;
      audio?.pause();
    },
    done,
  };
}
